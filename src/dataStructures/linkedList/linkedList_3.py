    def linkedListToList(self, myLinkedList):
        res = []
        node = myLinkedList.head
        while node is not None:
            res.append(node.value)
            node = node.next
        return res
    
    def nodesListToValues(self, nodesList):
        res = []
        for n in nodesList:     
            res.append(n.value)
        return res

    
